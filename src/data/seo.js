function staticMeta(path) {
  const m = STATIC[path]
  const nodes = path === '/' ? [websiteNode()] : [breadcrumbNode([HOME_CRUMB, { name: m.crumb, path }])]
  return { ...m, path, image: ogImage(m.og), jsonLd: graph(...nodes) }
}

function serviceMeta(s) {
  const path = `/services/${s.slug}`
  const name = `${s.title} in Hyderabad`
  const description = `${s.short} ${brand.name}, Mehdipatnam, Hyderabad.`
  return {
    path,
    title: name,
    description,
    image: ogImage(s.slug),
    priority: 0.8,
    jsonLd: graph(
      breadcrumbNode([HOME_CRUMB, { name: 'Services', path: '/#services' }, { name: s.title, path }]),
      serviceNode({ name, description, path, serviceType: s.title }),
      s.faqs?.length && faqNode(s.faqs),
    ),
  }
}

/** Meta for a Hyderabad landing page; `faqs` (from seoPages.js) adds the FAQ schema. */
export function seoPageMeta(slug, faqs) {
  const p = seoLinkBySlug[slug]
  const path = seoPath(p)
  const trail = slug === 'travel-agency-in-hyderabad' ? [HOME_CRUMB] : [HOME_CRUMB, { name: 'Hyderabad', path: '/travel-agency-in-hyderabad' }]
  return {
    path,
    title: p.title,
    description: p.description,
    image: ogImage(slug),
    priority: 0.9,
    jsonLd: graph(
      breadcrumbNode([...trail, { name: p.label, path }]),
      serviceNode({ name: p.label, description: p.description, path }),
      faqs?.length && faqNode(faqs),
    ),
  }
}

export const notFoundMeta = {
  title: 'Page not found',
  description: 'This page could not be found. Explore Al Balaagh Travels services in Hyderabad.',
  noindex: true,
}

/** Meta for a static page or a service page. */
export function metaFor(path) {
  if (STATIC[path]) return staticMeta(path)
  const slug = path.startsWith('/services/') ? path.slice('/services/'.length) : null
  const s = slug && services.find((x) => x.slug === slug)
  if (s && !s.path) return serviceMeta(s)
  return notFoundMeta
}

/** Every indexable route (used for the sitemap and the pre-built HTML files). */
export function indexableRoutes(seoFaqs = {}) {
  return [
    ...Object.keys(STATIC).map(staticMeta),
    ...seoLinks.map((p) => seoPageMeta(p.slug, seoFaqs[p.slug])),
    ...services.filter((s) => !s.path).map(serviceMeta),
  ]
}
